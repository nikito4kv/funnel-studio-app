"""Телефон из кнопки «отправить контакт» или из текста сообщения."""

from __future__ import annotations

import re


# Коды стран, которые встречаются у нашей аудитории. Нужны для номера,
# присланного ТЕКСТОМ БЕЗ «плюса»: там опознать страну больше не по чему.
# Двузначные коды (49, 90, 44) намеренно не берём – они начинаются так же,
# как российские номера с семёрки, и различить их по длине нельзя.
_COUNTRY_CODES = (
    "375",  # Беларусь
    "380",  # Украина
    "992", "993", "994", "995", "996", "998",  # Таджикистан…Узбекистан
    "374",  # Армения
    "373",  # Молдова
    "370", "371", "372",  # Литва, Латвия, Эстония
    "972",  # Израиль
    "976",  # Монголия
)


def _normalize_phone(raw: str | None) -> str | None:
    if not raw:
        return None
    digits = re.sub(r"\D", "", raw)
    if not digits:
        return None
    if digits.startswith("8") and len(digits) == 11:
        digits = "7" + digits[1:]
    # Семёрку дописываем ТОЛЬКО российскому мобильному (10 цифр с девятки).
    # Раньше её получал любой десятизначный номер – а это ломало иностранные,
    # которые приходят кнопкой без кода страны: к ним приклеивалась чужая «7».
    if len(digits) == 10 and digits.startswith("9"):
        digits = "7" + digits
    return digits


# Похоже ли сообщение на номер телефона и НИ НА ЧТО другое.
# Осторожно: люди пишут в бот и просто числа («10 000 подписчиков», номер
# заказа, дату). Поэтому проверяем не «есть ли 10 цифр внутри», а что весь
# текст – это номер: цифры, плюс, скобки, дефисы и пробелы, ничего больше.
_PHONE_TEXT_RE = re.compile(r"^[\s+()\-–—.]*\d[\d\s+()\-–—.]{8,20}$")


def phone_from_text(text: str | None) -> str | None:
    """Номер из свободного сообщения или None.

    Нужен, потому что часть людей не видит кнопку «отправить контакт» и просто
    пишет номер сообщением. Раньше такой номер уходил в инбокс и терялся:
    человек считал, что оставил контакт, а в базе его не было.
    """
    t = (text or "").strip()
    if not t or not _PHONE_TEXT_RE.match(t):
        return None
    digits = re.sub(r"\D", "", t)

    # Со знаком «+» – международный формат, принимаем ЛЮБУЮ страну: Казахстан,
    # Беларусь, Израиль, Германия. «+» и есть надёжный признак номера – ни
    # телеграмный id, ни сумма, ни дата с плюса не начинаются, поэтому здесь
    # достаточно проверить длину по стандарту E.164 (до 15 цифр).
    if t.lstrip().startswith("+"):
        return digits if 8 <= len(digits) <= 15 else None

    # Без «+» страну опознаём по коду в начале.
    # ⚠️ Девятка у российского формата обязательна: без неё телеграмный id вида
    # «1999044008» – ровно 10 цифр – проходил бы как телефон и записывался
    # человеку в карточку.
    if len(digits) == 11 and digits[0] in "78" and digits[1] == "9":
        return _normalize_phone(digits)
    if len(digits) == 10 and digits[0] == "9":
        return _normalize_phone(digits)
    if 11 <= len(digits) <= 13 and digits.startswith(_COUNTRY_CODES):
        return digits
    return None
